class Teacher:
    def __init__(
        self,
        teacher_id,
        full_name,
        specialization,
        degree,
        phone_number,
        status,
    ):
        self.teacher_id = teacher_id
        self.full_name = full_name
        self.specialization = specialization
        self.degree = degree
        self.phone_number = phone_number
        self.status = status
